/** Renders a spoken budget the way each locale writes a price ceiling. */
export function formatBudget(priceMinor: number, locale: Locale): string {
  const price = formatPrice(priceMinor, locale);
  return locale === 'uz'
    ? `${price}${t(locale, 'voiceUpTo')}`
    : `${t(locale, 'voiceUpTo')} ${price}`;
}

export type CopyKey = keyof typeof copy.ru;

export function t(locale: Locale, key: CopyKey): string {
  return copy[locale][key];
}

export function formatPrice(value: number, locale: Locale): string {
  const unit = locale === 'uz' ? 'so‘m' : 'сум';
  return `${new Intl.NumberFormat(locale === 'uz' ? 'uz-UZ' : 'ru-RU').format(value)} ${unit}`;
}

export function localizeCategory(name: string, locale: Locale): string {
  if (locale === 'ru') return name;
  const uzbek: Record<string, string> = {
    'аудио': 'Audio',
    'для дома': 'Uy uchun',
    'аксессуары': 'Aksessuarlar',
  };
  return uzbek[name.trim().toLocaleLowerCase('ru-RU')] ?? name;
}

/**
 * Human words for a handoff.
 *
 * `open`, `answered` and `buyer_requested_human` are database values. They were
 * reaching the screen unchanged, which is how a person ends up reading
 * `order_question` in a list of their own questions. Anything unrecognised
 * resolves to a neutral localized word rather than to the raw key: a value this
 * build has not heard of is still not English shorthand to show a shopper.
 */
export function labelForHandoffStatus(locale: Locale, status: string): string {
  const map: Record<string, CopyKey> = {
    open: 'statusOpen',
    answered: 'statusAnswered',
    closed: 'statusClosed',
    expired: 'statusExpired',
  };
  return t(locale, map[status] ?? 'statusClosed');
}

export function labelForHandoffReason(locale: Locale, reason: string): string {
  const map: Record<string, CopyKey> = {
    unknown_intent: 'reasonUnknownIntent',
    buyer_requested_human: 'reasonBuyerRequestedHuman',
    catalog_no_result: 'reasonCatalogNoResult',
    order_question: 'reasonOrderQuestion',
    seller_initiated: 'reasonSellerInitiated',
  };
  return t(locale, map[reason] ?? 'reasonOther');
}

export function labelForStatus(locale: Locale, status: string): string {
  const map: Partial<Record<string, CopyKey>> = {
    available: 'available', preorder: 'preorder', unavailable: 'unavailable',
    placed: 'placed', confirmed: 'confirmed', done: 'done', cancelled: 'cancelled',
    draft: 'draft', published: 'publishedStatus', archived: 'archived',
  };
  return map[status] ? t(locale, map[status]!) : status;
}

/**
 * The badge colour that goes with `labelForStatus` for an availability.
 *
 * Beside the label rather than in the component file: the two are always read
 * together, and a card, a detail sheet and the preview a seller checks before
 * publishing all have to agree on what «В наличии» looks like, or the preview
 * stops being a promise.
 */
export function availabilityTone(
  value: Product['availability'],
): 'positive' | 'warning' | 'negative' {
  return value === 'available' ? 'positive' : value === 'preorder' ? 'warning' : 'negative';
}

export function formatDate(value: string, locale: Locale): string {
  return new Intl.DateTimeFormat(locale === 'uz' ? 'uz-UZ' : 'ru-RU', {
    day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit',
  }).format(new Date(value));
}
